        val mealLog = newMealLog(logDate, mealType, meta)
        val filled = nutrientFiller.applyCached(items)
        val ruleTags = tagsFor(filled.map { it.name })
        val logItems = filled.mapIndexed { index, ingredient ->
            val m = ingredient.micros
            MealLogItemEntity(
                mealLogId = 0, // set by DAO
                name = ingredient.name,
                grams = ingredient.grams,
                calories = ingredient.calories,
                protein = ingredient.protein,
                fat = ingredient.fat,
                carbs = ingredient.carbs,
                fiber = ingredient.fiber,
                isDrink = ingredient.isDrink,
                waterMl = ingredient.waterMl,
                vitaminA = m.vitaminAMcg,
                vitaminC = m.vitaminCMg,
                vitaminD = m.vitaminDMcg,
                calcium = m.calciumMg,
                iron = m.ironMg,
                potassium = m.potassiumMg,
                sodium = m.sodiumMg,
                vitaminB12 = m.vitaminB12Mcg,
                folate = m.folateMcg,
                vitaminB6 = m.vitaminB6Mg,
                magnesium = m.magnesiumMg,
                zinc = m.zincMg,
                vitaminE = m.vitaminEMg,
                // Store the item itself as its single ingredient so the detail editor works.
                ingredientsJson = MealJson.encodeIngredients(listOf(ingredient)),
                ruleTags = DietaryRuleKind.tagsToDb(ruleTags.getOrElse(index) { emptySet() }),
                caffeineMg = ingredient.caffeineMg
            )
        }
        val mealLogId = mealLogDao.logMealWithItems(mealLog, logItems)
        enqueueInsights(mealLogId)
        maybeEnqueueNutrientCheck(mealLogId, filled)
        maybeNotifyDietary(logDate)
        return mealLogId
    }

