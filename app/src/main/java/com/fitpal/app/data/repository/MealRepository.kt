    /** Enqueue the background overview generation for a just-logged meal (survives leaving the app). */
    private fun enqueueInsights(mealLogId: Long) {
        val request = androidx.work.OneTimeWorkRequestBuilder<com.fitpal.app.ml.InsightsWorker>()
