/**
 * The facts about a meal being logged beyond its foods — when it was eaten, the situation tags, and
 * what the fasting check decided. Every logging path passes one (defaults = "now, untagged").
 */
data class MealLogMeta(
    /** When it was eaten (epoch millis); null = now (or now's clock time when logging another day). */
    val eatenAt: Long? = null,
    val timeSource: TimeSource = TimeSource.LOGGED,
    /** Situation tags, already joined (see [com.fitpal.app.domain.model.MealContext.format]). */
    val context: String? = null,
    /** "Log anyway" during a fast — see [MealLogEntity.loggedDuringFast]. */
    val loggedDuringFast: Boolean = false
)

/**
 * Build the [MealLogMeta] for a log from what the screen holds: the chosen meal time, the fasting
 * check's decision (a pass spent on a time wins over the screen's time), and the situation tags.
 */
fun mealLogMeta(
    logDate: LocalDate,
    eatenAt: com.fitpal.app.domain.model.EatenAt,
    decision: LogDecision = LogDecision.NONE,
    tags: Set<String> = emptySet()
): MealLogMeta {
    val time = decision.overrideTime ?: eatenAt.time
    val source = when {
        decision.overrideTime != null -> TimeSource.MANUAL
        eatenAt.time != null -> eatenAt.source
        else -> TimeSource.LOGGED
    }
    return MealLogMeta(
        eatenAt = time?.let { com.fitpal.app.domain.model.EatenAt(it).epochMillis(logDate) },
        timeSource = source,
        context = com.fitpal.app.domain.model.MealContext.format(tags),
        loggedDuringFast = decision.loggedDuringFast
    )
}

