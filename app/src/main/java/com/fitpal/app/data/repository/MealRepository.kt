    // ---- Filling database foods' gaps (fibre, vitamins, caffeine…) — see NutrientFiller ----

    /** Queue the background nutrient check when anything just logged still has a gap to fill. */
    private suspend fun maybeEnqueueNutrientCheck(mealLogId: Long, ingredients: List<Ingredient>) {
        if (!nutrientFiller.isConfigured()) return
        val caffeineOn = settingsRepository.caffeineSettings.value.enabled
        val needed = ingredients.any { nutrientFiller.needOf(it, caffeineOn) != NutrientFiller.Need.NONE }
        if (needed) runCatching { NutrientCheckWorker.enqueue(appContext, mealLogId) }
    }

    /**
     * The background check for one logged meal: ask the quick AI about every ingredient that still
     * has gaps (database foods: their zero fields + caffeine; anything else: caffeine, while the
     * tracker is on), cache the answers per food, and rewrite the items with the filled values —
     * only zeros are ever filled. Returns true when there's nothing (more) to do, false when the AI
     * couldn't run and it's worth retrying later.
     */
    suspend fun fillNutrientGaps(mealLogId: Long): Boolean {
        val items = mealLogDao.getItemsForMeal(mealLogId)
        // Nothing to do, or no way to ever do it (online AI off / no key) — don't keep retrying.
        if (items.isEmpty() || !nutrientFiller.isConfigured()) return true
        val caffeineOn = settingsRepository.caffeineSettings.value.enabled

        class Plan(val item: MealLogItemEntity, val ingredients: List<Ingredient>, val legacy: Boolean)
        val plans = items.mapNotNull { item ->
            val ings = ingredientsForItem(item)
            when {
                ings.isNotEmpty() -> Plan(item, nutrientFiller.applyCached(ings), legacy = false)
                // An older entry with no breakdown: only its caffeine can be checked, by name.
                caffeineOn && item.caffeineMg == null && item.calories >= 0f ->
                    Plan(item, listOf(itemAsIngredient(item).copy(caffeineMgPer100g = null)), legacy = true)
                else -> null
            }
        }
        val targets = plans.flatMap { plan ->
            plan.ingredients.mapNotNull { ing ->
                val need = nutrientFiller.needOf(ing, caffeineOn)
                nutrientFiller.targetFor(ing, plan.item.isDrink || ing.isDrink, need)
            }
        }
        val answers = if (targets.isEmpty()) emptyMap() else nutrientFiller.check(targets) ?: return false

        plans.forEach { plan ->
            // Re-apply from the cache (now holding the fresh answers) so every ingredient that shares
            // a food — or was answered in an earlier run — is filled the same way.
            val filled = nutrientFiller.applyCached(plan.ingredients)
            if (plan.legacy) {
                filled.first().caffeineMg?.let { mealLogDao.updateItemCaffeine(plan.item.id, it) }
            } else if (filled != ingredientsForItem(plan.item)) {
                updateItemIngredients(plan.item.id, filled)
            }
        }
        // Done when every target got an answer; otherwise leave the rest for a retry.
        return targets.all { answers.containsKey(it.key) }
    }

    /**
     * When the caffeine tracker is switched on: queue the caffeine check for the last two days'
     * meals that don't know their caffeine yet, so "in your body now" is right from the start.
     */
    suspend fun backfillCaffeine() {
        if (!nutrientFiller.isConfigured()) return
        val from = LocalDate.now().minusDays(1).format(dateFormat)
        mealLogDao.getMealLogIdsMissingCaffeine(from, todayString()).forEach { id ->
            runCatching { NutrientCheckWorker.enqueue(appContext, id) }
        }
    }

