    /** Duplicate a whole meal (all its dishes) onto another day. Keeps its category unless one is given. */
    suspend fun copyMealToDate(mealLogId: Long, date: String, mealType: String? = null) {
        val items = mealLogDao.getItemsForMeal(mealLogId)
        if (items.isEmpty()) return
        val type = mealType ?: mealLogDao.getMealTypeForMeal(mealLogId) ?: defaultMealType()
        // Carry the meal's name + situation tag too — a copy of "Sunday roast" is still Sunday roast.
        val original = mealLogDao.getMealLogById(mealLogId)
        val mealLog = MealLogEntity(
            date = date,
            mealType = type,
            name = mealLogDao.getMealName(mealLogId),
            context = original?.context,
            // Carry the coach's note too — a copy of the meal keeps its note (it's judged against the
            // day, and a copy lands on a nearby day, so it stays relevant). Copies bypass
            // InsightsWorker, so nothing overwrites it.
            coachingTipJson = original?.coachingTipJson
        )
        mealLogDao.logMealWithItems(mealLog, items.map { it.copy(id = 0, mealLogId = 0) })
    }

