    fun todayString(): String = LocalDate.now().format(dateFormat)

    /**
     * The eaten time for a meal logged to [logDate] with no time given: right now for today, else
     * now's clock time on that day (so the stored instant belongs to the day it's filed under).
     */
    private fun defaultTimestamp(logDate: String): Long {
        val now = LocalDateTime.now()
        val day = runCatching { LocalDate.parse(logDate) }.getOrNull() ?: return System.currentTimeMillis()
        if (day == now.toLocalDate()) return System.currentTimeMillis()
        return day.atTime(now.toLocalTime()).atZone(ZoneId.systemDefault()).toInstant().toEpochMilli()
    }

    /** Epoch millis for [time] on [logDate] (the meal-time pickers work in local clock time). */
    fun timestampFor(logDate: String, time: LocalTime): Long {
        val day = runCatching { LocalDate.parse(logDate) }.getOrNull() ?: LocalDate.now()
        return day.atTime(time.withSecond(0).withNano(0)).atZone(ZoneId.systemDefault()).toInstant().toEpochMilli()
    }

