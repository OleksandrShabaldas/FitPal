"""
Generates FitPal's alternative launcher icons (Settings -> Appearance -> App icon).

Writes, from the motif + colourway tables below:
  - app/src/main/res/drawable/ic_app_*_fg/bg/mono vectors (108 dp adaptive-icon layers),
  - app/src/main/res/mipmap-anydpi-v26/ic_app_*.xml adaptive icons,
  - the <activity-alias> block in AndroidManifest.xml between the GENERATED ICON ALIASES markers,
  - app/src/main/java/com/fitpal/app/ui/theme/AppIconCatalog.kt (the list the picker shows).

Run from the repo root:  python tools/gen_app_icons.py
Re-running is safe — every generated file is rewritten. The default icon (apple, Glow Ember) stays the
hand-made @mipmap/ic_launcher on the ".MainActivity" alias, so existing home-screen shortcuts survive.
"""
