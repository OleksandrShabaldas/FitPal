    track = (f'<path android:pathData="{circle(54, 54, 22)}" android:fillColor="#00000000" android:strokeColor="{fg}" '
             f'android:strokeAlpha="0.25" android:strokeWidth="7" />')
    return track + stroke("M54,32 A22,22 0 1,1 35,43", fg, 7) +         fill("M54,43 C60,50 61,55 58,60 C56,63 52,63 50,60 C47,56 49,50 54,43 Z", acc)


