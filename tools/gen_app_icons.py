def pixel_apple():
    rows = ["....32..", "...3.22.", ".111111.", "11141111", "11411111", "11111111", ".111111.", "..11.11."]
    col = {"1": "#E0584A", "2": "#8CC152", "3": "#8A5A3C", "4": "#F7B2A8"}
    out = []
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in col:
                out.append(fill(rect(34 + x * 5, 33 + y * 5, 5, 5), col[ch]))
    return "".join(out)


