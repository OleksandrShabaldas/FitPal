def adaptive(bg, fg, mono):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_app_icons.py - do not edit by hand. -->\n'
            f'<adaptive-icon {ANDROID}>\n    <background android:drawable="@drawable/{bg}" />\n'
            f'    <foreground android:drawable="@drawable/{fg}" />\n    <monochrome android:drawable="@drawable/{mono}" />\n</adaptive-icon>\n')


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    # Remove previously generated files so a renamed/dropped icon doesn't linger.
    for d in (DRAWABLE, MIPMAP):
        for name in os.listdir(d):
            if name.startswith("ic_app_"):
                os.remove(os.path.join(d, name))

    icons = []  # (id, label, group, colourway label, look hint, alias, mipmap)
    for motif, (mlabel, fn) in MOTIFS.items():
        mono = f"ic_app_{motif}_mono"
        write(os.path.join(DRAWABLE, mono + ".xml"), vector(fn("#FFFFFF", "#FFFFFF")))
        for cw, (clabel, hint, bgspec, fg, acc) in COLOURWAYS.items():
            icon_id = f"{motif}_{cw}"
            if icon_id == "apple_glow_ember":
                # The original icon — kept on the ".MainActivity" alias (see AndroidManifest.xml).
                icons.append((icon_id, mlabel, motif, clabel, hint, ".MainActivity", "ic_launcher"))
                continue
            bg = f"ic_app_bg_{cw}"
            fgname = f"ic_app_{icon_id}_fg"
            write(os.path.join(DRAWABLE, bg + ".xml"), vector(background(bgspec)))
            write(os.path.join(DRAWABLE, fgname + ".xml"), vector(fn(fg, acc)))
            write(os.path.join(MIPMAP, f"ic_app_{icon_id}.xml"), adaptive(bg, fgname, mono))
            icons.append((icon_id, mlabel, motif, clabel, hint, f".icon.{camel(icon_id)}", f"ic_app_{icon_id}"))
    for q, (label, bgcol, fn) in QUIRKY.items():
        icon_id = f"fun_{q}"
        bg = f"ic_app_bg_{icon_id}"
        fgname = f"ic_app_{icon_id}_fg"
        mono = f"ic_app_{icon_id}_mono"
        write(os.path.join(DRAWABLE, bg + ".xml"), vector(background(("flat", bgcol))))
        body = fn()
        write(os.path.join(DRAWABLE, fgname + ".xml"), vector(body))
        write(os.path.join(DRAWABLE, mono + ".xml"), vector(re.sub(r'android:(fill|stroke)Color="#[0-9A-Fa-f]{6}"', lambda m: f'android:{m.group(1)}Color="#FFFFFF"', body)))
        write(os.path.join(MIPMAP, f"ic_app_{icon_id}.xml"), adaptive(bg, fgname, mono))
        icons.append((icon_id, label, "fun", "", "", f".icon.{camel(icon_id)}", f"ic_app_{icon_id}"))

    write_manifest(icons)
    write_catalog(icons)
    print(f"Generated {len(icons)} icons ({len(icons) - 1} aliases + the original).")


def camel(s):
    return "".join(p.capitalize() for p in s.split("_"))


def write_manifest(icons):
    with open(MANIFEST, encoding="utf-8") as f:
        text = f.read()
    begin = "<!-- BEGIN GENERATED ICON ALIASES"
    end = "<!-- END GENERATED ICON ALIASES -->"
    blocks = []
    for icon_id, label, grp, clabel, hint, alias, mip in icons:
        enabled = "true" if alias == ".MainActivity" else "false"
        comment = ("The original icon. Keeps the launcher component name the app has always had, so an existing "
                   "home-screen shortcut survives; FitPalActivity is the real activity.") if alias == ".MainActivity" else icon_id
        blocks.append(
            f"""        <!-- {comment} -->
        <activity-alias
            android:name="{alias}"
            android:enabled="{enabled}"
            android:exported="true"
            android:icon="@mipmap/{mip}"
            android:roundIcon="@mipmap/{mip}"
            android:label="@string/app_name"
            android:targetActivity=".FitPalActivity">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>""")
    gen = (f"{begin} (tools/gen_app_icons.py — one per launcher icon; exactly one is enabled) -->\n"
           + "\n".join(blocks) + f"\n        {end}")
    if begin in text:
        text = re.sub(re.escape(begin) + r".*?" + re.escape(end), lambda m: gen, text, flags=re.S)
    else:
        raise SystemExit("Add the GENERATED ICON ALIASES markers to AndroidManifest.xml first.")
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def write_catalog(icons):
    lines = []
    for icon_id, label, grp, clabel, hint, alias, mip in icons:
        lines.append(f'        AppIcon("{icon_id}", "{label}", "{grp}", "{clabel}", "{hint}", "com.fitpal.app{alias}", R.mipmap.{mip}),')
    text = f"""package com.fitpal.app.ui.theme

import com.fitpal.app.R

// Generated by tools/gen_app_icons.py — do not edit by hand.

/**
 * One launcher icon: [group] is its motif ("apple", "ring", "carrot", "sprout") or "fun";
 * [lookHint] ("GLOW:OCEAN", "PAPER:LIGHT", …) is the look it was made to match; [alias] is the
 * <activity-alias> that carries it.
 */
data class AppIcon(
    val id: String,
    val label: String,
    val group: String,
    val colourway: String,
    val lookHint: String,
    val alias: String,
    val mipmap: Int
)

object AppIconCatalog {{
    const val DEFAULT_ID = "apple_glow_ember"

    val all: List<AppIcon> = listOf(
{chr(10).join(lines)}
    )

    fun byId(id: String?): AppIcon? = all.firstOrNull {{ it.id == id }}
}}
"""
    with open(CATALOG, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


if __name__ == "__main__":
    main()
