def background(spec):
    kind, val = spec
    if kind == "flat":
        return f'<path android:pathData="M0,0 h108 v108 h-108 z" android:fillColor="{val}" />'
    items = "".join(
        f'<item android:offset="{i / (len(val) - 1):.2f}" android:color="{c}" />' for i, c in enumerate(val))
    if kind == "radial":
        grad = f'<gradient android:type="radial" android:centerX="74" android:centerY="32" android:gradientRadius="120">{items}</gradient>'
    else:
        grad = f'<gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">{items}</gradient>'
    return (f'<path android:pathData="M0,0 h108 v108 h-108 z"><aapt:attr name="android:fillColor">{grad}'
            f'</aapt:attr></path>')


