AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'
ANDROID = 'xmlns:android="http://schemas.android.com/apk/res/android"'


# ---------------------------------------------------------------- shape helpers (108 x 108 viewport)
def circle(cx, cy, r):
    return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z"


def ellipse(cx, cy, rx, ry):
    return f"M{cx - rx},{cy} a{rx},{ry} 0 1,0 {2 * rx},0 a{rx},{ry} 0 1,0 {-2 * rx},0 Z"


def rect(x, y, w, h, r=0):
    if r <= 0:
        return f"M{x},{y} h{w} v{h} h{-w} Z"
    return (f"M{x + r},{y} h{w - 2 * r} a{r},{r} 0 0 1 {r},{r} v{h - 2 * r} a{r},{r} 0 0 1 {-r},{r} "
            f"h{-(w - 2 * r)} a{r},{r} 0 0 1 {-r},{-r} v{-(h - 2 * r)} a{r},{r} 0 0 1 {r},{-r} Z")


def fill(d, color):
    return f'<path android:pathData="{d}" android:fillColor="{color}" />'


def stroke(d, color, width, cap="round"):
    return (f'<path android:pathData="{d}" android:fillColor="#00000000" android:strokeColor="{color}" '
            f'android:strokeWidth="{width}" android:strokeLineCap="{cap}" android:strokeLineJoin="round" />')


def group(body, rotation=0, px=54, py=54, scale=1.0):
    return (f'<group android:rotation="{rotation}" android:pivotX="{px}" android:pivotY="{py}" '
            f'android:scaleX="{scale}" android:scaleY="{scale}">{body}</group>')


def vector(body):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_app_icons.py - do not edit by hand. -->\n'
            f'<vector {ANDROID} {AAPT} android:width="108dp" android:height="108dp" '
            f'android:viewportWidth="108" android:viewportHeight="108">\n    {body}\n</vector>\n')


